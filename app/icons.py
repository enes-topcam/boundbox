_icons = {}
_renderers = {}
_DIR = Path(tempfile.gettempdir()) / "etiketleme-ui"


def _svg(name, color, width=1.75):
    inner = _PATHS[name].replace("currentColor", color)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{inner}</svg>')


def _pixmap(name, color, size, dpr):
    key = (name, color)
    r = _renderers.get(key)
    if r is None:
        r = _renderers[key] = QSvgRenderer(QByteArray(_svg(name, color).encode()))
    pm = QPixmap(round(size * dpr), round(size * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    r.render(p, QRectF(0, 0, pm.width(), pm.height()))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name, color, disabled=None):
    """name: Lucide adı (ör. 'folder-open'), color: '#rrggbb'. disabled: pasif hâlin rengi."""
    key = (name, color, disabled)
    ic = _icons.get(key)
    if ic is None:
        ic = QIcon()
        for size in (14, 16, 18, 20, 24):
            for dpr in (1.0, 1.25, 1.5, 2.0):
                ic.addPixmap(_pixmap(name, color, size, dpr), QIcon.Mode.Normal)
                if disabled:
                    ic.addPixmap(_pixmap(name, disabled, size, dpr), QIcon.Mode.Disabled)
        _icons[key] = ic
    return ic


def file(name, color, width=1.75):
    """QSS'te url(...) ile kullanmak için renkli SVG'yi dosyaya yazar, yolunu döner."""
    _DIR.mkdir(parents=True, exist_ok=True)
    path = _DIR / f"{name}-{color.lstrip('#')}-{str(width).replace('.', '_')}.svg"
    if not path.exists():
        path.write_text(_svg(name, color, width), encoding="utf-8")
    return path.as_posix()


def dot_file(fill, ring=None, size=16):
    """Radyo düğmesi içi gibi dolu daire (QSS için)."""
    _DIR.mkdir(parents=True, exist_ok=True)
    path = _DIR / f"dot-{fill.lstrip('#')}-{(ring or '').lstrip('#')}.svg"
    if not path.exists():
        ring_svg = f'<circle cx="12" cy="12" r="11" fill="{ring}"/>' if ring else ""
        path.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">{ring_svg}'
                        f'<circle cx="12" cy="12" r="4.5" fill="{fill}"/></svg>', encoding="utf-8")
    return path.as_posix()
